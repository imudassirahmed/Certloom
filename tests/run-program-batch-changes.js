'use strict';
const assert = require('node:assert/strict');
const { BatchDraft } = require('../admin/assets/program-workspace.js');
const item = (id, patch = {}) => ({ id, revision: `revision-${id}`, patch: { name: `Batch ${id}`, code: `B${id}`, active: true, start_date: '2026-01-01', end_date: '2026-12-31', batch_field_requirement: { score: 'required' }, ...patch } });
let checks = 0;
const check = (test, label) => { assert(test, label); checks++; };
const model = new BatchDraft();
model.stage(item(1), { name: 'Revised' });
model.stage({ ...item(1), revision: 'newer-server-revision' }, { code: 'MBA-2026' });
check(model.changes.get('1').revision === 'revision-1', 'Subsequent edits retain the revision originally edited, so concurrent changes are detected.');
check(model.get(item(1)).patch.name === 'Revised' && model.get(item(1)).patch.code === 'MBA-2026', 'Edits merge without dropping earlier edits.');
check(model.get(item(1)).patch.batch_field_requirement.score === 'required', 'Bulk date or design edits preserve the field contract.');
model.bulk([item(1), item(2)], { active: '0', batch_template_id: '12' });
check(model.changes.get('1').patch.name === 'Revised' && model.changes.get('2').patch.active === '0', 'Bulk editing preserves prior individual edits and explicit inactive values.');
const before = model.serialize();
assert.throws(() => model.bulk([item(1), item(3, { start_date: '2027-01-01' })], { end_date: '2026-09-01' }), /dates/); checks++;
check(before === model.serialize(), 'A conflicting date in one batch stages no part of the bulk change.');
const limited = new BatchDraft([], 2);
limited.stage(item(1), { name: 'One' });
assert.throws(() => limited.bulk([item(2), item(3)], { active: false }), /limit/); checks++;
check(limited.changes.size === 1, 'Bulk changes exceeding the limit leave existing drafts intact.');
limited.stage(item(2), { start_date: '' });
limited.stage(item(2), { active: false });
check(limited.changes.size === 2 && limited.get(item(2)).patch.active === false, 'The bound limits unique changed batches, not the number of edits.');
assert.throws(() => limited.stage(item(3), { name: 'Three' }), /limit/); checks++;
model.undo('1'); check(!model.changes.has('1') && model.changes.has('2'), 'Undo affects only its selected batch.');
model.stage({ id: 0, key: 'new-intake', patch: {} }, { name: 'Autumn intake', active: true });
const recovered = new BatchDraft(JSON.parse(model.serialize()));
check(recovered.get({ id: 0, key: 'new-intake', patch: {} }).patch.name === 'Autumn intake', 'Unsaved new Program batches round-trip through form draft recovery.');
check(BatchDraft.validDates({ start_date: '', end_date: '2026-01-01' }) && BatchDraft.validDates({ start_date: '2026-01-01', end_date: '' }), 'Clearing one date is an explicit valid bulk change.');
console.log(`${checks} checks, 0 failures`);
